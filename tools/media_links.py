"""Links that never break (phase D2, MP section 6): every video by a key of ``resources/media.toml``.

``--write`` makes, from the registry:

- a go page per video, ``docs/go/<key>/index.html``, a redirect GitHub Pages serves at ``<site>/go/<key>/`` - what
  README, docs, posts and other videos' descriptions link;
- the player's list, ``frontend/src/player/media.generated.ts`` (key -> YouTube id; the help plays by key);
- each link in the README and the docs from a YouTube address of a registered video to its go-link (done once; after
  that the rule below keeps them so).

``--check`` exits 1 when a generated file is not as ``--write`` would make it, or when a file of the repository
links a video on YouTube directly outside the registry, the generated files and the demo page's data.

Standard library only.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path
from typing import Any

import tomllib

PROJECT = Path(__file__).resolve().parents[1]
REGISTRY = PROJECT / "resources" / "media.toml"
GO = PROJECT / "docs" / "go"
PLAYER = PROJECT / "frontend" / "src" / "player" / "media.generated.ts"

DIRECT = re.compile(r"https?://(?:youtu\.be/|(?:www\.)?youtube\.com/watch\?v=)([\w-]{11})")
ALLOWED = (
    "resources/media.toml",
    "docs/go/",
    "frontend/src/player/media.generated.ts",
    # the demo page's data, written by tools/demo_showcase.py from the songs' own records
    "docs/demo-showcase.js",
    "docs/demo-showcase.md",
    "docs/index.html",
    # designs quote addresses as examples; the records of what was published keep theirs
    "docs/design/",
    "docs/test-reports/",
    "CHANGELOG.md",
    "tools/media_links.py",
    "tests/unit/test_media_links.py",
    "tests/unit/test_demo_showcase.py",
)
SCANNED = (".md", ".ts", ".vue", ".py", ".html", ".json", ".mjs", ".toml")


def registry() -> dict[str, Any]:
    data: dict[str, Any] = tomllib.loads(REGISTRY.read_text(encoding="utf-8"))
    keys = [v["key"] for v in data["video"]]
    if len(keys) != len(set(keys)):
        raise SystemExit("resources/media.toml: a key is given twice")
    for video in data["video"]:
        if not re.fullmatch(r"[a-z0-9-]+", video["key"]) or not re.fullmatch(r"[\w-]{11}", video["youtube"]):
            raise SystemExit(f"resources/media.toml: {video['key']!r} - a key of a-z, 0-9 and -, an id of 11")
    return data


def go_link(data: dict[str, Any], key: str) -> str:
    return f"{data['site']}/go/{key}/"


def go_page(video: dict[str, Any]) -> str:
    url = f"https://youtu.be/{video['youtube']}"
    title = html.escape(f"Plenio · {video['title']}")
    return (
        '<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex">'
        f"<title>{title}</title>\n"
        f'<link rel="canonical" href="{url}">\n'
        f'<meta http-equiv="refresh" content="0; url={url}">\n'
        f"<script>location.replace({json.dumps(url)} + location.hash)</script>\n"
        f'<a href="{url}">{html.escape(video["title"])} on YouTube</a>\n'
    )


def player_module(data: dict[str, Any]) -> str:
    rows = "\n".join(f"  {json.dumps(v['key'])}: {json.dumps(v['youtube'])}," for v in data["video"])
    playlists = "\n".join(
        f"  {json.dumps(p['key'])}: {json.dumps(p['youtube'])}," for p in data.get("playlist", [])
    )
    return (
        "// Generated by tools/media_links.py from resources/media.toml - do not edit.\n"
        "/** Every video by its key: the YouTube id it plays (a re-upload changes the registry, not the help). */\n"
        f"export const MEDIA: Record<string, string> = {{\n{rows}\n}}\n\n"
        f"export const PLAYLISTS: Record<string, string> = {{\n{playlists}\n}}\n"
    )


def wanted_files(data: dict[str, Any]) -> dict[Path, str]:
    files = {GO / v["key"] / "index.html": go_page(v) for v in data["video"]}
    files[PLAYER] = player_module(data)
    return files


def relinked(text: str, data: dict[str, Any]) -> str:
    """``text`` with every direct link of a registered video turned into its go-link."""
    by_id = {v["youtube"]: v["key"] for v in data["video"]}
    return DIRECT.sub(lambda m: go_link(data, by_id[m.group(1)]) if m.group(1) in by_id else m.group(0), text)


def tracked() -> list[Path]:
    """The repository's files as git knows them (tracked or new, not ignored)."""
    import subprocess

    out = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=PROJECT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
        timeout=60,
    ).stdout
    return [PROJECT / name for name in sorted(set(out.split("\0"))) if name and (PROJECT / name).is_file()]


def direct_links() -> list[str]:
    """Files that link a video on YouTube directly, outside the allowed ones."""
    found = []
    for path in tracked():
        rel = path.relative_to(PROJECT).as_posix()
        if path.suffix not in SCANNED or rel.startswith(ALLOWED):
            continue
        if rel.startswith(
            ("web/js/", "plenio/player/static/", "plenio/player/guest_static/", "plenio/third_party/")
        ):
            continue  # builds and vendored code
        text = path.read_text(encoding="utf-8", errors="replace")
        if DIRECT.search(text):
            found.append(rel)
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = registry()
    wanted = wanted_files(data)
    known = {GO / v["key"] / "index.html" for v in data["video"]}
    gone = [p for p in GO.glob("*/index.html") if p not in known] if GO.is_dir() else []
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_bytes().decode() != text]
    if args.write:
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(wanted[path].encode())
        for path in gone:
            path.unlink()
            path.parent.rmdir()
        relinked_files = 0
        for name in ("README.md", "docs", "frontend/src", "plenio", "SECURITY.md"):
            root = PROJECT / name
            for path in [root] if root.is_file() else sorted(root.rglob("*")):
                rel = path.relative_to(PROJECT).as_posix()
                if not path.is_file() or path.suffix not in SCANNED or rel.startswith(ALLOWED):
                    continue
                text = path.read_bytes().decode()
                new = relinked(text, data)
                if new != text:
                    path.write_bytes(new.encode())
                    relinked_files += 1
        print(
            f"media: {len(stale)} generated file(s) written, {len(gone)} removed, {relinked_files} relinked"
        )
        return 0
    problems = [f"{p.relative_to(PROJECT).as_posix()}: not as resources/media.toml says" for p in stale]
    problems += [f"{p.relative_to(PROJECT).as_posix()}: no video of that key any more" for p in gone]
    problems += [
        f"{rel}: links YouTube directly - link the video's go-link (resources/media.toml)"
        for rel in direct_links()
    ]
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print("run python tools/media_links.py --write", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
